async function saveResultToAPI(resultData) {
    try {
        const response = await fetch(API_URL, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify(resultData)
        });
        
        const data = await response.json();
        return data.success;
    } catch (error) {
        console.error('Ошибка сохранения в облако:', error);
        saveResultToLocalStorage(resultData);
        return true;
    }
}

async function getResultsFromAPI(quizId = null) {
    try {
        const url = quizId ? `${API_URL}?quizId=${quizId}` : API_URL;
        const response = await fetch(url);
        const data = await response.json();
        
        if (data.success) {
            return data.data;
        }
        return [];
    } catch (error) {
        console.error('Ошибка загрузки из облака:', error);
        return getResultsFromLocalStorage(quizId);
    }
}

function saveResultToLocalStorage(resultData) {
    try {
        let leaders = JSON.parse(localStorage.getItem('quizLeaders') || '[]');
        leaders.push({
            name: resultData.playerClass,
            score: resultData.score,
            quiz: resultData.quizTitle,
            quizId: resultData.quizId,
            time: resultData.time,
            date: new Date().toLocaleDateString('ru-RU')
        });
        localStorage.setItem('quizLeaders', JSON.stringify(leaders));
    } catch (e) {
        console.error('Ошибка локального сохранения:', e);
    }
}

function getResultsFromLocalStorage(quizId = null) {
    try {
        const leaders = JSON.parse(localStorage.getItem('quizLeaders') || '[]');
        if (quizId) {
            return leaders.filter(leader => leader.quizId === quizId).map(item => ({
                playerClass: item.name,
                score: item.score,
                time: item.time,
                quizId: item.quizId,
                quizTitle: item.quiz
            }));
        }
        return leaders.map(item => ({
            playerClass: item.name,
            score: item.score,
            time: item.time,
            quizId: item.quizId,
            quizTitle: item.quiz
        }));
    } catch (e) {
        console.error('Ошибка загрузки локальных данных:', e);
        return [];
    }
}

function playCorrectSound() {
    if (!soundEnabled) return;
    
    const sound = document.getElementById('correct-sound');
    sound.currentTime = 0; 
    sound.volume = 1.0; 
    sound.play().catch(e => {
        console.log('Не удалось воспроизвести звук:', e);
        soundEnabled = false;
        updateSoundButton();
    });
}

function playWrongSound() {
    if (!soundEnabled) return;
    
    const sound = document.getElementById('wrong-sound');
    sound.currentTime = 0;
    sound.volume = 0.3; 
    sound.play().catch(e => {
        console.log('Не удалось воспроизвести звук:', e);
        soundEnabled = false;
        updateSoundButton();
    });
}

function toggleSound() {
    soundEnabled = !soundEnabled;
    updateSoundButton();
}

function updateSoundButton() {
    const soundToggle = document.getElementById('sound-toggle');
    const soundIcon = document.getElementById('sound-icon');
    
    if (soundEnabled) {
        soundIcon.textContent = '🔊';
        soundToggle.classList.remove('muted');
    } else {
        soundIcon.textContent = '🔇';
        soundToggle.classList.add('muted');
    }
}

